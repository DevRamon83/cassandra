CREATE TABLE bankroll (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE NOT NULL UNIQUE,
    budget NUMERIC NOT NULL
);

CREATE TABLE bets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE NOT NULL,
    bankroll BIGINT REFERENCES bankroll(id) NOT NULL,
    season VARCHAR(9) NOT NULL,
    stake DECIMAL(5, 2) NOT NULL,
    won BOOLEAN DEFAULT NULL
);

CREATE TYPE user_prediction AS ENUM ('under', 'over', 'goal', 'no_goal', '1', 'x', '2');

CREATE TABLE items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE NOT NULL,
    bet_id BIGINT REFERENCES bets(id) ON DELETE CASCADE NOT NULL,
    match_id BIGINT REFERENCES matches(id) NOT NULL,
    odds DECIMAL(5, 2) NOT NULL,
    prediction user_prediction NOT NULL,
    won BOOLEAN DEFAULT NULL
);

CREATE INDEX idx_bets ON items(bet_id);
CREATE INDEX idx_bets ON items(season);
CREATE INDEX idx_match ON items(match_id);

