CREATE TABLE bankroll (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE NOT NULL UNIQUE,
    current_budget NUMERIC NOT NULL,
    initial_budget NUMERIC NOT NULL,
    season VARCHAR(9) NOT NULL
);

CREATE TABLE bets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE NOT NULL,
    season VARCHAR(9) NOT NULL,
    stake DECIMAL(5, 2) NOT NULL,
    bonus DECIMAL(7, 2) NOT NULL,
    won BOOLEAN DEFAULT NULL
);

CREATE TYPE user_prediction AS ENUM ('under', 'over', 'goal', 'no_goal', '1', 'x', '2');

CREATE TABLE items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE NOT NULL,
    bet_id BIGINT REFERENCES bets(id) ON DELETE CASCADE NOT NULL,
    match_id BIGINT REFERENCES matches(id) NOT NULL,
    odds DECIMAL(5, 2) NOT NULL,
    prediction user_prediction NOT NULL,
    won BOOLEAN DEFAULT NULL
);

CREATE INDEX idx_items_bet_id ON items(bet_id);
CREATE INDEX idx_bets_season ON bets(season);
CREATE INDEX idx_items_match_id ON items(match_id);


ALTER TABLE public.bankroll ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.items ENABLE ROW LEVEL SECURITY;